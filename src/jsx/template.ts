/**
 * Template Functions
 *
 * Provides template caching for compiled JSX. The Babel plugin extracts
 * static HTML into template strings and uses these functions to create
 * and clone cached template elements.
 *
 * @module jsx/template
 *
 * ## Known limitations
 *
 * None.
 */

//=============================================
// Template Creation
//=============================================

/**
 * Creates a cached template element from an HTML string.
 *
 * The Babel plugin calls this function with static HTML extracted from JSX.
 * Returns a function that clones the template content on each call.
 *
 * @param html - Static HTML string
 * @param _isImportNode - Set for custom elements, unused: Signy clones
 * @param isSVG - The HTML is wrapped in an `<svg>` to unwrap
 * @param isMathML - The root is a MathML element outside `<math>`
 * @returns A function that returns a cloned DOM node
 *
 * @example
 * ```typescript
 * // Generated by Babel plugin:
 * const _tmpl$ = template('<div class="container"><span></span></div>');
 *
 * function render() {
 *   const el = _tmpl$(); // Call the function to get a cloned node
 *   // ... set up dynamic parts
 *   return el;
 * }
 * ```
 */
export function template(
  html: string,
  _isImportNode?: boolean,
  isSVG?: boolean,
  isMathML?: boolean
): () => Node {
  let node: Node | undefined;

  const create = (): Node => {
    const tmpl = document.createElement('template');
    // The parser only switches to MathML inside <math>
    tmpl.innerHTML = isMathML ? `<math>${html}</math>` : html;
    // For SVG, we need to get the first child of the first child (unwrap the SVG wrapper)
    return isSVG || isMathML
      ? tmpl.content.firstChild!.firstChild!
      : tmpl.content.firstChild!;
  };

  // Return a function that clones the cached node
  const fn = (): Node => {
    return (node || (node = create())).cloneNode(true);
  };

  // Add cloneNode method for compatibility with some usage patterns
  (fn as unknown as { cloneNode: () => Node }).cloneNode = fn;

  return fn;
}
