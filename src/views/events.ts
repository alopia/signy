/**
 * Event Delegation
 *
 * A handler for a common bubbling event (click, input, keydown...) is stored
 * on its element, and one listener per event on the document runs it. A list
 * of 1,000 rows with two handlers each adds no listeners. Used by `h()`,
 * `html` and compiled JSX.
 *
 * During a delegated handler, `event.currentTarget` is the element the
 * handler is on, as with addEventListener().
 *
 * @module views/events
 *
 * ## Known limitations
 *
 * **Detached elements**: An event on an element outside the document never
 * reaches the document listener. Use `on:click` for those.
 *
 * **Listener order**: A delegated handler runs when the event reaches the
 * document, after native listeners on its ancestors. stopPropagation() in a
 * delegated handler stops the other delegated handlers only.
 */

//=============================================
// Types
//=============================================

/**
 * Handler for delegated events
 */
type DelegatedHandler = (event: Event) => void;

/**
 * Bound handler with data: [handler, data]
 */
type BoundHandler = [(data: unknown, event: Event) => void, unknown];

/**
 * Extended element with delegated event handlers
 */
interface DelegatedElement extends Element {
  [key: `$$${string}`]: unknown;
}

//=============================================
// Module State
//=============================================

/**
 * Events that bubble and are common on many elements at once. The same list
 * as Solid and the JSX compiler.
 */
export const DELEGATED_EVENTS: ReadonlySet<string> = new Set([
  'beforeinput',
  'click',
  'dblclick',
  'contextmenu',
  'focusin',
  'focusout',
  'input',
  'keydown',
  'keyup',
  'mousedown',
  'mousemove',
  'mouseout',
  'mouseover',
  'mouseup',
  'pointerdown',
  'pointermove',
  'pointerout',
  'pointerover',
  'pointerup',
  'touchend',
  'touchmove',
  'touchstart',
]);

/**
 * Set of events that have been delegated
 */
const delegatedEvents = new Set<string>();

//=============================================
// Event Delegation Setup
//=============================================

/**
 * Sets up event delegation for specified events.
 *
 * Called by compiled JSX to ensure delegated events are handled.
 * Events are only delegated once, even if called multiple times.
 *
 * @param eventNames - Array of event names to delegate
 *
 * @example
 * ```typescript
 * // Generated by Babel plugin at end of module:
 * delegateEvents(['click', 'input', 'change']);
 * ```
 */
export function delegateEvents(eventNames: string[]): void {
  for (const name of eventNames) delegateEvent(name);
}

/**
 * Delegates one event.
 *
 * @internal
 */
export function delegateEvent(name: string): void {
  if (!delegatedEvents.has(name)) {
    delegatedEvents.add(name);
    document.addEventListener(name, handleDelegatedEvent);
  }
}

/**
 * Stores a handler on its element and delegates its event.
 *
 * @internal
 */
export function setDelegatedHandler(
  element: Element,
  name: string,
  handler: EventListener
): void {
  (element as DelegatedElement)[`$$${name}`] = handler;
  delegateEvent(name);
}

/**
 * Listens on a closed shadow root. The document only sees the host of an
 * event from inside it, so the handlers inside would never run.
 *
 * @internal
 */
export function delegateShadowRoot(root: ShadowRoot): void {
  for (const name of new Set([...DELEGATED_EVENTS, ...delegatedEvents])) {
    root.addEventListener(name, handleDelegatedEvent);
  }
}

/** Reports an error the way the browser does for a native listener */
function reportHandlerError(error: unknown): void {
  if (typeof reportError === 'function') reportError(error);
  else
    setTimeout(() => {
      throw error;
    });
}

/**
 * Handles a delegated event by walking up the DOM tree
 */
function handleDelegatedEvent(event: Event): void {
  const handlerKey = `$$${event.type}` as const;
  const dataKey = `$$${event.type}Data` as const;
  // The document, or a closed shadow root that handles its own nodes
  const listener = event.currentTarget;

  let current: EventTarget | null = listener;
  Object.defineProperty(event, 'currentTarget', {
    configurable: true,
    get: () => current,
  });

  // composedPath() includes nodes inside open shadow roots
  try {
    for (const node of event.composedPath()) {
      if (node === listener) break;
      const target = node as DelegatedElement;
      const handler = target[handlerKey] as
        DelegatedHandler | BoundHandler | undefined;

      if (handler) {
        current = target;
        // Each handler stands alone, as native listeners do: one that throws
        // is reported and the ones above it still run
        try {
          if (Array.isArray(handler)) {
            // Bound event: [handler, data]
            const [fn, data] = handler;
            fn.call(target, data, event);
          } else if (target[dataKey] !== undefined) {
            // Compiled bound event: $$click plus $$clickData
            (handler as unknown as BoundHandler[0]).call(
              target,
              target[dataKey],
              event
            );
          } else {
            handler.call(target, event);
          }
        } catch (error) {
          reportHandlerError(error);
        }

        // Stop if the handler called stopPropagation
        if (event.cancelBubble) break;
      }
    }
  } finally {
    // Also after a throwing handler, so the event is left as it was found
    current = listener;
  }
}

//=============================================
// Event Helpers
//=============================================

/**
 * Clears all delegated events.
 * Useful for testing or when unmounting an app.
 */
export function clearDelegatedEvents(): void {
  for (const name of delegatedEvents) {
    document.removeEventListener(name, handleDelegatedEvent);
  }
  delegatedEvents.clear();
}
